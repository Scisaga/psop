import fs from 'node:fs';
import path from 'node:path';
import { chromium } from '@playwright/test';

const phase = process.argv[2] || 'before';
const origin = process.env.PSOP_ORIGIN || 'http://127.0.0.1:8780';
const repo = path.resolve(import.meta.dirname, '../../..');
const root = path.join(repo, 'build/connection-sites-review');
const out = path.join(root, phase);
fs.mkdirSync(out, { recursive: true });
const catalog = await (await fetch(origin + '/api/workspaces')).json();
const snapshot = phase === 'before' ? 'dkp-84f6829a25a82fefaf1d' : catalog.workspaces.find(w => w.id === 'microduck').selectedSnapshotId;
const browser = await chromium.launch({ channel: 'chrome', headless: true });
const page = await browser.newPage({ viewport: { width: 1600, height: 900 }, reducedMotion: 'reduce' });
await page.addInitScript(() => localStorage.setItem('psop.workbench.inspector-width', '360'));
const errors = [];
page.on('pageerror', error => errors.push(error.message));
const camera = '0.30,-0.32,0.23,0,0,0.105';
const query = new URLSearchParams({ workspace: 'microduck', snapshot, part: 'part:microduck:fa9ee2f71faafb88', detail: 'interfaces', labels: '0', grid: '0', explode: '0', camera });
await page.goto(`${origin}/#explorer?${query}`, { timeout: 360000 });
await page.locator('[data-scene-ready="true"]').waitFor({ timeout: 360000 });
await page.waitForFunction(() => document.querySelector('.scene-canvas')?.dataset.cameraFlight === 'settled');
await page.screenshot({ path: path.join(out, 'hip-1600x900.png') });
const desktop = await page.locator('.inspector').innerText();
const desktopBounds = await page.locator('.inspector').boundingBox();
await page.setViewportSize({ width: 1100, height: 800 });
await page.screenshot({ path: path.join(out, 'hip-1100x800.png') });
const scripts = await page.locator('script[src]').evaluateAll(elements => elements.map(element => element.getAttribute('src')));
const stylesheets = await page.locator('link[rel="stylesheet"]').evaluateAll(elements => elements.map(element => element.getAttribute('href')));
const record = { phase, snapshot, camera, url: page.url(), desktopBounds, desktop, scripts, stylesheets, errors };
fs.writeFileSync(path.join(out, 'capture.json'), JSON.stringify(record, null, 2));
await browser.close();
console.log(JSON.stringify({ phase, snapshot, errors, out }));
