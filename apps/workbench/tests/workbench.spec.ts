let data: PrototypeData;
let target: Part, foot: Part, ankle: Part, sole: Part, servo: Part;
let footHole: LogicalHole, servoPattern: FeaturePattern, surfaceObservation: ReferenceObservation, patternObservation: ReferenceObservation;
let leg: Part, housing: MountingInterface, housingSites: MountingSite[], standardMount: ReferenceMount, legSlot: SlotFeature;
const explorerUrl = (partId: string, selection?: Record<string, string>, snapshot = selectedSnapshotId) => '/#explorer?' + new URLSearchParams({
  workspace: device.id, snapshot, part: partId, explode: '0', ...selection,
});

test.beforeAll(async () => {
  test.setTimeout(120000);
  // Exercise the real HTTP boundary and reuse the server's validation cache;
  // test collection and worker startup must not each replay the full package.
  const response = await fetch(`http://127.0.0.1:8780/api/workspaces/${device.id}/snapshots/${selectedSnapshotId}/view`, { signal: AbortSignal.timeout(115000) });
  if (!response.ok) throw new Error(await response.text());
  data = await response.json();
  expect(data.meta.validation?.profile, 'Publish and select the connector-direction 1.8 snapshot').toBe('psop.hardware.source-model/1.8');
  target = data.parts.find(p => p.meshKey === 'motor_support')!;
  foot = data.parts.find(p => p.meshKey === 'foot_right')!;
  ankle = data.parts.find(p => p.meshKey === 'ankle_right')!;
  sole = data.parts.find(p => p.meshKey === 'sole_right')!;
  servo = data.parts.find(p => p.id === 'part:microduck:0820b4025f26a004')!;
  footHole = data.analysis!.logical_holes!.find(item => item.owner_ref === foot.id && item.kind === 'stepped_bore')!;
  servoPattern = data.analysis!.feature_patterns!.find(item => item.owner_ref === servo.id && item.geometry.type === 'circular' && item.geometry.origin[0] < 0 && item.logical_hole_refs.length === 4)!;
  surfaceObservation = data.analysis!.reference_observations!.find(item => item.kind === 'finite_surface_overlap' && item.participants.some(p => p.part_ref === foot.id) && item.participants.some(p => p.part_ref === sole.id))!;
  patternObservation = data.analysis!.reference_observations!.find(item => item.kind === 'hole_pattern_alignment' && item.participants.some(p => p.part_ref === servo.id) && item.participants.some(p => p.part_ref === ankle.id) && item.member_observation_refs!.length === 4)!;
  leg = data.parts.find(part => part.id === 'part:microduck:7f4fefc3c6de90f1')!;
  housing = data.analysis!.mounting_interfaces!.find(item => item.owner_ref === servo.id)!;
  housingSites = data.analysis!.mounting_sites!.filter(site => housing.member_site_refs.includes(site.id));
  standardMount = data.analysis!.reference_mounts!.find(item => item.participants.some(p => p.part_ref === servo.id) && item.participants.some(p => p.part_ref === leg.id))!;
  legSlot = data.analysis!.slot_features!.find(item => item.owner_ref === leg.id && item.kind === 'rounded_rectangle_opening' && Math.abs(item.geometry.width_m - .005) < .00001 && Math.abs(item.geometry.length_m - .010) < .00001)!;
});

