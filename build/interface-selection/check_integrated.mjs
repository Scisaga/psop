import fs from 'node:fs';
import path from 'node:path';
import { chromium } from '../../apps/workbench/node_modules/playwright-core/index.mjs';
const root = path.resolve('build/interface-selection');
const captures = JSON.parse(fs.readFileSync(path.join(root, 'before/capture.json'), 'utf8'));
const output = path.join(root, 'integrated'); fs.mkdirSync(output, { recursive: true });
const browser = await chromium.launch({ channel: 'chrome', headless: true });
const records = [];
for (const record of captures.records.filter(item => item.variant === 'close')) {
 const page = await browser.newPage({ viewport:{width:1600,height:1000}, reducedMotion:'reduce' });
 const errors=[]; page.on('pageerror',error=>errors.push(error.message));
 await page.route('**/api/**',async route=>{const response=await route.fetch({url:route.request().url().replace(':8781/',':8780/')});await route.fulfill({response});});
 const started=Date.now();
 await page.goto(record.url.replace(':8780/',':8781/'));
 await page.locator('[data-scene-ready="true"]').waitFor({timeout:60000});
 await page.waitForFunction(()=>document.querySelector('.scene-canvas')?.dataset.cameraFlight==='settled');
 const readyMs=Date.now()-started;
 await page.screenshot({path:path.join(output,record.target+'-normal.png')});
 await page.locator('.scene-analysis-tools>summary').click();
 await page.getByRole('checkbox',{name:'整件特征边线',exact:true}).check();
 if(await page.locator('.scene-canvas').getAttribute('data-mesh-edges')!=='source_creases') throw new Error('Explicit edge display did not activate');
 await page.screenshot({path:path.join(output,record.target+'-debug-edges.png')});
 await page.getByRole('checkbox',{name:'整件特征边线',exact:true}).uncheck();
 await page.getByRole('checkbox',{name:'原始三角边',exact:true}).check();
 await page.getByRole('checkbox',{name:'原始面片法向',exact:true}).check();
 await page.screenshot({path:path.join(output,record.target+'-debug-facets.png')});
 await page.getByRole('checkbox',{name:'原始三角边',exact:true}).uncheck();
 await page.getByRole('checkbox',{name:'原始面片法向',exact:true}).uncheck();
 await page.locator('.scene-analysis-tools>summary').click();
 await page.getByRole('button',{name:'清除几何标注',exact:true}).click();
 if(await page.locator('.scene-canvas').getAttribute('data-opening-highlight')) throw new Error('Selection not cleared');
 if(await page.locator('.scene-canvas').getAttribute('data-mesh-edges')!=='hidden') throw new Error('Debug edges leaked after switch-off');
 await page.screenshot({path:path.join(output,record.target+'-cleared.png')});
 records.push({target:record.target,readyMs,errors,scene:await page.locator('.scene-canvas').evaluate(el=>({...el.dataset}))});
 await page.close();
}
await browser.close();
fs.writeFileSync(path.join(output,'checks.json'),JSON.stringify({records},null,2));
console.log(JSON.stringify({records:records.map(({target,readyMs,errors})=>({target,readyMs,errors}))}));
